"""
alpha_agent.fundamental_jobs — Stage 10.2 CANONICAL FUNDAMENTAL JOBS + PLANNER.

The reusable capability the AlphaAgent needs to OPERATE the downstream path from
the released historical identity layer (Stage 10.1) to real survivorship-safe
historical PIT fundamental evaluation, through the SAME durable ``ResearchQueue``
and one-job-per-cycle fair scheduler — Claude builds the capability; the
AlphaAgent prioritizes, creates, claims and executes the jobs and (when the
measured activation gate opens) generates + runs the fundamental experiment.

A distinct Stage 10.2 campaign (origin ``stage10.2-fundamentals``, the new
allowlisted ``fundamentals.`` lane prefix) that reuses EXACTLY the existing
infrastructure: the durable ``CampaignStore`` (mapped-CIK cursor + append-only
supersession), the ``BulkArchiveDownloader`` (resumable/atomic/SHA-256), the new
``SecCompanyFactsIndex`` (durable bulk companyfacts index), the ``PitFundamentals
Store`` (leakage-safe PIT view) and the measured ``fundamental_readiness``
contract. Every job is BOUNDED, IDEMPOTENT, RESTART-SAFE, FAILURE-ISOLATED,
DEDUPLICATED and CONFIG-CONTROLLED; completion flags are stamped by the HANDLER
on success (never at plan time) so a failed step re-runs and none is silently
skipped. No second worker/queue/scheduler.

Lanes (all origin ``stage10.2-fundamentals``, prefix ``fundamentals.``):
  * fundamentals.bulk_inventory   (DATA_ACQUISITION) — inventory owned facts +
    DOWNLOAD companyfacts.zip (restart-safe/atomic/SHA-256).
  * fundamentals.mapped_cik_plan  (DATA_ACQUISITION) — derive the resolved
    historical CIK target set + seed/supersede the durable campaign cursor.
  * fundamentals.bulk_index       (DATA_ACQUISITION) — stream companyfacts.zip
    into the durable fact index: catalogue every member, materialise the target
    concepts for the mapped CIKs; record per-CIK campaign progress.
  * fundamentals.pit_materialize  (DATA_VALIDATION) — build the leakage-safe PIT
    store from the index for the mapped CIKs; measure observations + concepts.
  * fundamentals.coverage_measure (DATA_VALIDATION) — per-rebalance PIT readiness
    for every candidate on the survivorship-safe historical universe.
  * fundamentals.readiness_recheck(DATA_VALIDATION) — measured mapping + measured
    readiness + the measured activation gate (never flips a switch).
  * fundamentals.activation_recheck(DATA_VALIDATION) — record the final measured
    activation-gate result. The experiment itself is generated by the tournament
    tick when the gate opens — never enqueued here.

Pure stdlib; deterministic; the only side effects are the durable companyfacts
index, the durable campaign cursor, immutable artifacts and enqueues into the
shared research queue. No operational-ledger / order / fill / signal / trade-
decision / model-promotion / prediction touch anywhere.
"""
