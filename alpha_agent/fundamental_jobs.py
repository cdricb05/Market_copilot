def _fund_pit_materialize(ctx: FundamentalJobContext, job) -> tuple:
    """Part 4: build the leakage-safe PIT store from the durable index for the
    resolved historical CIKs and measure the materialised observations + per-
    candidate concept coverage. The durable facts already live in the index
    (filed-date bounded, amendments preserved); this validates + records the
    measured PIT depth. Stamps the epoch flag on success."""
    OK, BLK, RETRY = _outcomes()
    if ctx.companyfacts_index is None:
        return BLK, {"real_work": LANE_FUND_PIT_MATERIALIZE,
                     "blocker": "NO_COMPANYFACTS_INDEX",
                     "reason": "companyfacts index not configured",
                     "disposition": "DATA_HOLD"}
    store, ciks = _build_pit_store(ctx)
    summ = store.coverage_summary()
    per_candidate = {sig: len(store.ciks_with_candidate(sig))
                     for sig in ctx.signals}
    pit_summary = {
        "pit_observations": summ["pit_observations"],
        "distinct_ciks": summ["distinct_ciks"],
        "concepts_present": summ["concepts_present"],
        "availability_start": summ["availability_start"],
        "availability_end": summ["availability_end"],
        "ciks_with_candidate": per_candidate,
        "mapped_ciks": len(ciks)}
    ctx.store.set_meta("stage102_pit_summary", json.dumps(pit_summary))
    ctx.store.set_meta("stage102_pit_complete", _epoch(ctx))
    detail = {"real_work": LANE_FUND_PIT_MATERIALIZE, **pit_summary,
              "disposition": "DATA_HOLD", "no_automatic_promotion": True}
    detail["artifact"] = write_artifact(ctx.artifact_root, job.lane, detail,
                                        clock=ctx.clock)
    return OK, detail


def _fund_coverage_measure(ctx: FundamentalJobContext, job) -> tuple:
    """Part 5: measure per-rebalance PIT readiness for every candidate on the
    survivorship-safe historical universe (identity universe on each date + the
    RESOLVED map + the measured PIT facts). Aggregate current-company counts can
    never unlock — the survivorship denominator + the per-date fact coverage keep
    it honest. Persists a durable readiness snapshot; stamps the epoch flag."""
    OK, BLK, RETRY = _outcomes()
    from . import fundamental_readiness as _fr
    pit_store, _ = _build_pit_store(ctx)
    snapshot = {}
    for sig in ctx.signals:
        rr = _fr.measured_readiness_from_store(
            ctx.store, sig, ctx.cfg9, pit_store=pit_store,
            rebalance_dates=ctx.rebalance_dates, index_name=ctx.index_name)
        snapshot[sig] = {
            "sufficient": rr.get("sufficient"), "blocker": rr.get("blocker"),
            "mapping_available": rr.get("mapping_available"),
            "valid_scored_periods": rr.get("valid_scored_periods"),
            "median_coverage_pct": rr.get("median_coverage_pct"),
            "median_historical_mapping_coverage_pct":
                rr.get("median_historical_mapping_coverage_pct"),
            "min_eligible_names": rr.get("min_eligible_names"),
            "median_eligible_names": rr.get("median_eligible_names"),
            "subperiod_coverage": rr.get("subperiod_coverage"),
            "earliest_usable_formation_date":
                rr.get("earliest_usable_formation_date"),
            "latest_usable_formation_date":
                rr.get("latest_usable_formation_date")}
    ctx.store.set_meta("stage102_readiness_snapshot", json.dumps(snapshot))
    ctx.store.set_meta("stage102_coverage_complete", _epoch(ctx))
    detail = {"real_work": LANE_FUND_COVERAGE_MEASURE,
              "rebalance_dates": len(ctx.rebalance_dates),
              "readiness": snapshot, "disposition": "DATA_HOLD",
              "no_automatic_promotion": True}
    detail["artifact"] = write_artifact(ctx.artifact_root, job.lane, detail,
                                        clock=ctx.clock)
    return OK, detail


def _fund_readiness_recheck(ctx: FundamentalJobContext, job) -> tuple:
    """Part 5/6: re-evaluate the MEASURED mapping status + the MEASURED activation
    gate for every candidate from the measured PIT store. Records the gate result;
    NEVER flips a switch. Stamps the epoch flag on success."""
    OK, BLK, RETRY = _outcomes()
    from . import fundamental_readiness as _fr
    pit_store, _ = _build_pit_store(ctx)
    mapping = _fr.historical_mapping_status_from_store(ctx.store, ctx.cfg9)
    gate = {}
    for sig in ctx.signals:
        g = _fr.historical_fundamental_experiment_allowed(
            ctx.cfg9, store=ctx.store, signal=sig, pit_store=pit_store)
        gate[sig] = {"allowed": g["allowed"], "activation_mode":
                     g["activation_mode"], "mapping_available":
                     g["mapping_available"], "readiness_sufficient":
                     g["readiness_sufficient"], "readiness_blocker":
                     g.get("readiness_blocker"), "diagnostic": g["diagnostic"]}
    ctx.store.set_meta("stage102_gate_snapshot", json.dumps(gate))
    ctx.store.set_meta("stage102_readiness_complete", _epoch(ctx))
    detail = {"real_work": LANE_FUND_READINESS_RECHECK,
              "measured_mapping_available": mapping["available"],
              "measured_mapping_coverage_pct": mapping.get(
                  "measured_coverage_pct"),
              "gate": gate, "safety_switch_flipped": False,
              "disposition": "DATA_HOLD", "no_automatic_promotion": True}
    detail["artifact"] = write_artifact(ctx.artifact_root, job.lane, detail,
                                        clock=ctx.clock)
    return OK, detail


def _fund_activation_recheck(ctx: FundamentalJobContext, job) -> tuple:
    """Part 6/7: record the FINAL measured activation-gate result (OPEN/CLOSED,
    activation mode, exact reason). When OPEN, the tournament tick — not this
    handler — generates the canonical fundamental experiment. Stamps the epoch
    flag; never enqueues an experiment; never flips a switch."""
    OK, BLK, RETRY = _outcomes()
    from . import fundamental_readiness as _fr
    pit_store, _ = _build_pit_store(ctx)
    primary = ctx.signals[0] if ctx.signals else "gross_profitability"
    g = _fr.historical_fundamental_experiment_allowed(
        ctx.cfg9, store=ctx.store, signal=primary, pit_store=pit_store)
    any_open = False
    for sig in ctx.signals:
        gg = _fr.historical_fundamental_experiment_allowed(
            ctx.cfg9, store=ctx.store, signal=sig, pit_store=pit_store)
        any_open = any_open or bool(gg["allowed"])
    ctx.store.set_meta("stage102_activation_open", "1" if any_open else "0")
    ctx.store.set_meta("stage102_activation_complete", _epoch(ctx))
    detail = {"real_work": LANE_FUND_ACTIVATION_RECHECK,
              "activation_mode": g["activation_mode"],
              "activation_open_any_signal": any_open,
              "primary_signal": primary, "primary_allowed": g["allowed"],
              "diagnostic": g["diagnostic"], "reason": g["reason"],
              "note": ("when open, the tournament tick generates the canonical "
                       "fundamental experiment; never enqueued here"),
              "safety_switch_flipped": False, "disposition": "DATA_HOLD",
              "no_automatic_promotion": True}
    detail["artifact"] = write_artifact(ctx.artifact_root, job.lane, detail,
                                        clock=ctx.clock)
    return OK, detail


