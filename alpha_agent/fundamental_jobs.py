def _utc_now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


# --------------------------------------------------------------------------- #
# Fundamental job context (all heavy dependencies injected for testability).
# --------------------------------------------------------------------------- #
@dataclass
class FundamentalJobContext:
    store: _hi.IdentityStore                     # the Stage 10 identity store
    companyfacts_index: Any                      # SecCompanyFactsIndex
    campaign_store: Any                          # acquisition_campaign.CampaignStore
    artifact_root: str
    rebalance_dates: "list[str]" = field(default_factory=list)
    cfg9: dict = field(default_factory=dict)
    stage102: dict = field(default_factory=dict)  # the stage10_2 config block
