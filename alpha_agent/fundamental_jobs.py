def _fund_bulk_inventory(ctx: FundamentalJobContext, job) -> tuple:
    """Part 1: inventory the owned companyfacts + DOWNLOAD the companyfacts bulk
    archive with the existing restart-safe/atomic/SHA-256 downloader (looped to
    completion inside a wall-clock budget; a transport interruption is RETRYABLE
    and resumes from the durable byte checkpoint). No parsing here."""
    import time as _time
    from . import sec_bulk_download as _bulk
    OK, BLK, RETRY = _outcomes()
    cfg = _cfg(ctx)
    final, manifest = _companyfacts_paths(cfg)
    url = cfg.get("companyfacts_url")
    if final is None or not url:
        return BLK, {"real_work": LANE_FUND_BULK_INVENTORY,
                     "blocker": "STAGE102_NOT_CONFIGURED",
                     "reason": "bulk_root/companyfacts_url not configured",
                     "disposition": "DATA_HOLD"}
    if ctx.transport is None:
        return BLK, {"real_work": LANE_FUND_BULK_INVENTORY,
                     "blocker": "NO_HTTP_TRANSPORT",
                     "reason": "no SEC HTTP transport injected",
                     "disposition": "DATA_HOLD"}
    owned_facts = 0
    if callable(ctx.read_normalized):
        try:
            owned_facts = sum(1 for _ in ctx.read_normalized(
                "FUNDAMENTAL_FACT", limit=int(cfg.get("owned_scan_limit",
                                                      2000))))
        except Exception:  # noqa: BLE001 - inventory is best-effort
            owned_facts = 0
    dl = _bulk.BulkArchiveDownloader(
        url=url, dest_dir=final.parent, name="companyfacts",
        headers=_ua_headers(cfg),
        disk_budget_bytes=int(cfg.get("disk_budget_bytes", 4 * 1024 ** 3)),
        transport=ctx.transport)
    budget = float(cfg.get("download_time_budget_seconds", 1800))
    started = _time.monotonic()
    last: dict = {}
    while True:
        last = dl.download_segment()
        if last.get("complete") or not last.get("ok"):
            break
        if (_time.monotonic() - started) >= budget:
            break
    detail = {"real_work": LANE_FUND_BULK_INVENTORY,
              "owned_fundamental_facts_scanned": owned_facts,
              "companyfacts_url": url,
              "download_disposition": last.get("disposition"),
              "progress_pct": last.get("progress_pct"),
              "archive_sha256": last.get("sha256"),
              "archive_bytes": last.get("total_bytes"),
              "archive_exists": final.exists(),
              "complete": bool(last.get("complete")),
              "disposition": "DATA_HOLD", "no_automatic_promotion": True}
    detail["artifact"] = write_artifact(ctx.artifact_root, job.lane, detail,
                                        clock=ctx.clock)
    if last.get("complete"):
        return OK, detail
    detail["reason"] = last.get("reason", "download in progress; resuming")
    return RETRY, detail


def _fund_mapped_cik_plan(ctx: FundamentalJobContext, job) -> tuple:
    """Part 3: derive the resolved historical CIK target set from the canonical
    ACTIVE RESOLVED mappings and seed / append-only-supersede the durable campaign
    cursor. Unresolved securities are EXCLUDED (never a current-survivor
    substitution). The mapped epoch is stamped so the plan re-runs only when the
    resolved mapping changes."""
    OK, BLK, RETRY = _outcomes()
    ciks = _resolved_ciks(ctx)
    if not ciks:
        return BLK, {"real_work": LANE_FUND_MAPPED_CIK_PLAN,
                     "blocker": "NO_RESOLVED_HISTORICAL_CIKS",
                     "reason": ("no ACTIVE RESOLVED security->CIK mapping in the "
                                "identity store; run the Stage 10.1 bridge first"),
                     "disposition": "DATA_HOLD"}
    fingerprint = _hi.content_hash(ciks)
    campaign_id = DEFAULT_CAMPAIGN_ID
    rev = None
    if ctx.campaign_store is not None:
        try:
            rev = ctx.campaign_store.ensure_campaign_revision(
                DEFAULT_CAMPAIGN_ID, kind=CAMPAIGN_KIND, universe=ciks,
                universe_source="stage10_1_resolved_mappings",
                universe_fingerprint=fingerprint,
                batch_size=int(_cfg(ctx).get("cik_batch", 500)))
            campaign_id = rev.get("campaign_id", DEFAULT_CAMPAIGN_ID)
        except Exception as exc:  # noqa: BLE001 - campaign seed never fatal
            rev = {"error": type(exc).__name__}
    ctx.store.set_meta("stage102_mapped_epoch", _mapping_version(ctx))
    ctx.store.set_meta("stage102_campaign_id", campaign_id)
    ctx.store.set_meta("stage102_mapped_cik_count", str(len(ciks)))
    ctx.store.set_meta("stage102_mapped_fingerprint", fingerprint)
    detail = {"real_work": LANE_FUND_MAPPED_CIK_PLAN,
              "mapped_cik_count": len(ciks), "campaign_id": campaign_id,
              "universe_fingerprint": fingerprint, "campaign_revision": rev,
              "sample_ciks": ciks[:10], "disposition": "DATA_HOLD",
              "no_automatic_promotion": True}
    detail["artifact"] = write_artifact(ctx.artifact_root, job.lane, detail,
                                        clock=ctx.clock)
    return OK, detail


def _fund_bulk_index(ctx: FundamentalJobContext, job) -> tuple:
    """Part 2 + 4: stream the companyfacts archive into the durable fact index,
    cataloguing every member (complete, not sampled) and materialising the target
    concepts for the mapped-CIK allowlist. Bounded per step + wall-clock;
    idempotent (facts UNIQUE per cik/tag/unit/period/accession, amendments
    preserved); restart-safe (durable member cursor). Records per-CIK campaign
    progress (attempted/completed/missing)."""
    OK, BLK, RETRY = _outcomes()
    cfg = _cfg(ctx)
    idx = ctx.companyfacts_index
    if idx is None:
        return BLK, {"real_work": LANE_FUND_BULK_INDEX,
                     "blocker": "NO_COMPANYFACTS_INDEX",
                     "reason": "companyfacts index not configured",
                     "disposition": "DATA_HOLD"}
    final, _ = _companyfacts_paths(cfg)
    if final is None or not final.exists():
        return BLK, {"real_work": LANE_FUND_BULK_INDEX,
                     "blocker": "COMPANYFACTS_ARCHIVE_ABSENT",
                     "reason": ("companyfacts.zip not present; run "
                                "fundamentals.bulk_inventory first"),
                     "disposition": "DATA_HOLD"}
    ciks = _resolved_ciks(ctx)
    ahash = _companyfacts_hash(cfg)
    r = idx.index_companyfacts_archive(
        final, archive_hash=ahash, allowlist_ciks=ciks,
        target_tags=_target_tags(ctx),
        member_step=int(cfg.get("index_member_step", 5000)),
        time_budget_seconds=float(cfg.get("index_time_budget_seconds", 1200)))
    # Record per-CIK campaign progress (idempotent; a re-recorded COMPLETED CIK is
    # a no-op). A mapped CIK with no companyfacts member once the archive is fully
    # streamed is an honest MISSING (recorded as failed, exact reason).
    campaign_id = ctx.store.get_meta("stage102_campaign_id") or DEFAULT_CAMPAIGN_ID
    materialized = []
    missing = []
    if ctx.campaign_store is not None:
        for c in ciks:
            m = idx.member(c)
            if m and m.get("materialized"):
                materialized.append(c)
            elif r.get("complete") and (m is None):
                missing.append(c)
        try:
            failed = [(c, "NO_COMPANYFACTS_MEMBER") for c in missing]
            ctx.campaign_store.record_results(
                campaign_id, succeeded=materialized, failed=failed)
            ctx.campaign_store.record_batch(
                campaign_id, run_date=ctx.now()[:10],
                progress=bool(materialized), origin=ORIGIN_102,
                stop_reason=None if r.get("complete") else "IN_PROGRESS",
                metrics={"ciks_completed": len(materialized),
                         "records_added": r.get("facts_indexed"),
                         "issuers_covered": r.get("ciks_materialized")})
        except Exception:  # noqa: BLE001 - campaign bookkeeping never fatal
            pass
    detail = {"real_work": LANE_FUND_BULK_INDEX, "archive_sha256": ahash,
              "allowlist_size": r.get("allowlist_size"),
              "members_done": r.get("members_done"),
              "total_members": r.get("total_members"),
              "members_cataloged": r.get("members_cataloged"),
              "ciks_materialized": r.get("ciks_materialized"),
              "facts_indexed": r.get("facts_indexed"),
              "malformed_members": r.get("malformed_members"),
              "complete": bool(r.get("complete")),
              "mapped_ciks_materialized": len(materialized),
              "mapped_ciks_missing": len(missing),
              "elapsed_seconds": r.get("elapsed_seconds"),
              "disposition": "DATA_HOLD", "no_automatic_promotion": True}
    detail["artifact"] = write_artifact(ctx.artifact_root, job.lane, detail,
                                        clock=ctx.clock)
    return OK, detail


