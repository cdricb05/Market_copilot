def dispatch_fundamental_job(job, ctx: FundamentalJobContext) -> tuple:
    """Dispatch ONE claimed Stage 10.2 job to its lane handler. Bounded, idempotent
    (a job already recorded in the identity store's processed_jobs is a no-op
    COMPLETED), restart-safe and failure-isolated (a handler exception becomes a
    bounded RETRYABLE — never crashes the drain). Returns (outcome, detail)."""
    from . import autonomous_research as _ar
    lane = str(getattr(job, "lane", ""))
    handler = _LANE_HANDLERS.get(lane)
    if handler is None:
        return _ar.OUTCOME_BLOCKED_SPECIFIC, {
            "reason": "no fundamental handler for lane %s" % lane}
    job_key = "%s:%s" % (lane, _hi.content_hash(job.payload or {})[:16])
    if ctx.store.already_processed(job_key):
        return _ar.OUTCOME_COMPLETED, {"real_work": lane,
                                       "idempotent_skip": True,
                                       "disposition": "DATA_HOLD"}
    try:
        outcome, detail = handler(ctx, job)
    except Exception as exc:  # noqa: BLE001 - never crash the drain
        return _ar.OUTCOME_RETRYABLE, {
            "reason": "fundamental handler raised: %s" % type(exc).__name__,
            "lane": lane}
    if outcome == _ar.OUTCOME_COMPLETED:
        ctx.store.mark_processed(job_key, job_id=getattr(job, "job_id", None),
                                 kind=lane)
    detail.setdefault("lane", lane)
    return outcome, detail


# --------------------------------------------------------------------------- #
# Autonomous dependency planner. The AlphaAgent generates its OWN next Stage 10.2
# job: it inspects the download / index / campaign / readiness state, picks the
# single highest-value next action and enqueues exactly one idempotent job (at
# most one live fundamental job at a time).
# --------------------------------------------------------------------------- #
def _has_live_fundamental_job(queue) -> bool:
    from . import autonomous_research as _ar
    for st in (_ar.STATE_QUEUED, _ar.STATE_RUNNING, _ar.STATE_RETRYABLE):
        for j in queue.list_jobs(state=st, limit=1000):
            if str(j.lane).startswith(FUNDAMENTAL_LANE_PREFIX) and \
                    j.origin == ORIGIN_102:
                return True
    return False


def _enqueue102(queue, ctx: FundamentalJobContext, lane: str, category: str,
                reason: str, payload: dict, *,
                max_attempts: Optional[int] = None) -> dict:
    from . import autonomous_research as _ar  # noqa: F401 - parity import
    p = dict(payload or {})
    p["prioritization_reason"] = reason
    p["planned_at"] = ctx.now()
    p["stage"] = "10.2"
    pr = int((ctx.stage102 or {}).get("priority", DEFAULT_PRIORITY))
    job_id = queue.enqueue(category, lane=lane, payload=p, priority=pr,
                           origin=ORIGIN_102, max_attempts=max_attempts)
    ctx.store.set_meta("last_stage102_reason", "%s | %s" % (lane, reason))
    return {"job_id": job_id, "lane": lane, "category": category,
            "reason": reason, "origin": ORIGIN_102, "payload": p}


def _plan_stage102(queue, ctx: FundamentalJobContext) -> Optional[dict]:
    """Drive the Stage 10.2 campaign in strict dependency order: download
    companyfacts.zip -> plan the mapped-CIK target set -> stream the fact index ->
    materialise PIT -> measure per-rebalance readiness -> re-check the measured
    activation gate. Returns the SINGLE highest-value next step, or None when the
    whole downstream path is measured for the current epoch (so the tournament /
    identity / companyfacts reclaim the slot). The AlphaAgent — not Claude —
    generates each next action, and (when the gate opens) the tournament tick
    generates the fundamental experiment."""
    from . import autonomous_research as _ar
    cfg = _cfg(ctx)
    idx = ctx.companyfacts_index
    # 1) Acquire the SEC companyfacts bulk archive (restart-safe download).
    final, _ = _companyfacts_paths(cfg)
    if final is None or not final.exists():
        return _enqueue102(
            queue, ctx, LANE_FUND_BULK_INVENTORY, _ar.CAT_DATA_ACQUISITION,
            "SEC companyfacts bulk archive not yet acquired; download it "
            "(restart-safe, atomic, SHA-256)", {"stage": "download"},
            max_attempts=int(cfg.get("download_max_attempts", 24)))
    # 2) Derive the resolved mapped-CIK target set + seed the durable campaign.
    mvh = _mapping_version(ctx)
    if (ctx.store.get_meta("stage102_mapped_epoch") or "") != mvh:
        return _enqueue102(
            queue, ctx, LANE_FUND_MAPPED_CIK_PLAN, _ar.CAT_DATA_ACQUISITION,
            "derive the resolved historical CIK target set + seed the durable "
            "companyfacts campaign cursor", {"mapping_version": mvh})
    # 3) Stream the companyfacts archive into the durable fact index.
    st = idx.archive_status("companyfacts") if idx is not None else {}
    if not st.get("complete"):
        return _enqueue102(
            queue, ctx, LANE_FUND_BULK_INDEX, _ar.CAT_DATA_ACQUISITION,
            "companyfacts fact index incomplete: %s/%s members streamed"
            % (st.get("members_done", 0), st.get("total_members", 0)),
            {"members_done": st.get("members_done", 0),
             "total_members": st.get("total_members", 0),
             "facts_indexed": st.get("facts_indexed", 0)},
            max_attempts=int(cfg.get("index_max_attempts", 48)))
    # 4-7) Materialise PIT, measure readiness, re-check the activation gate —
    #      each ONCE per epoch (the HANDLER stamps the epoch flag on success).
    epoch = _epoch(ctx)
    if ctx.store.get_meta("stage102_pit_complete") != epoch:
        return _enqueue102(
            queue, ctx, LANE_FUND_PIT_MATERIALIZE, _ar.CAT_DATA_VALIDATION,
            "materialise leakage-safe PIT observations for the resolved "
            "historical CIKs from the bulk index", {"epoch": epoch})
    if ctx.store.get_meta("stage102_coverage_complete") != epoch:
        return _enqueue102(
            queue, ctx, LANE_FUND_COVERAGE_MEASURE, _ar.CAT_DATA_VALIDATION,
            "measure per-rebalance PIT readiness for every candidate on the "
            "survivorship-safe historical universe", {"epoch": epoch})
    if ctx.store.get_meta("stage102_readiness_complete") != epoch:
        return _enqueue102(
            queue, ctx, LANE_FUND_READINESS_RECHECK, _ar.CAT_DATA_VALIDATION,
            "re-evaluate measured mapping + measured activation gate from "
            "canonical state", {"epoch": epoch})
    if ctx.store.get_meta("stage102_activation_complete") != epoch:
        return _enqueue102(
            queue, ctx, LANE_FUND_ACTIVATION_RECHECK, _ar.CAT_DATA_VALIDATION,
            "record the final measured activation-gate result (the tournament "
            "generates the experiment when open)", {"epoch": epoch})
    return None


def plan_next_fundamental_job(queue, ctx: FundamentalJobContext, *,
                              cfg: Optional[dict] = None) -> Optional[dict]:
    """Determine and enqueue the SINGLE highest-value next Stage 10.2 action, or
    return None when the downstream campaign is measured for the current epoch (so
    the queue is never flooded and the tournament is never permanently starved). At
    most ONE live fundamental job exists at a time (idempotent). Driven only when
    Stage 10.2 is enabled AND the companyfacts index exists."""
    cfg = cfg or ctx.stage102 or {}
    if not cfg.get("enabled") or not cfg.get("planner_enabled", True):
        return None
    if ctx.companyfacts_index is None:
        return None
    if _has_live_fundamental_job(queue):
        return None
    return _plan_stage102(queue, ctx)


