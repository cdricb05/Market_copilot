def _cfg(ctx: FundamentalJobContext) -> dict:
    return ctx.stage102 or {}


def _ua_headers(cfg: dict) -> dict:
    ua = "%s %s" % (cfg.get("user_agent_product",
                            "paper-trader-alpha-agent/2.0"),
                    cfg.get("contact_email") or "")
    return {"User-Agent": ua.strip(), "Accept-Encoding": "identity"}


def _companyfacts_paths(cfg: dict):
    root = cfg.get("bulk_root")
    if not root:
        return None, None
    return (Path(root) / "companyfacts.zip",
            Path(root) / "companyfacts.manifest.json")


def _companyfacts_hash(cfg: dict) -> Optional[str]:
    _, manifest = _companyfacts_paths(cfg)
    if manifest and manifest.exists():
        try:
            return json.loads(manifest.read_text(encoding="utf-8")).get("sha256")
        except (OSError, ValueError):
            return None
    return None


def _resolved_ciks(ctx: FundamentalJobContext) -> list:
    """Every canonical CIK with an ACTIVE RESOLVED mapping (the survivorship-safe
    historical universe — current + delisted). Deterministic sorted set."""
    out = []
    for s in ctx.store.list_securities(limit=1000000):
        mp = ctx.store.active_mapping(s["security_id"])
        if mp and mp.get("status") == _hi.STATUS_RESOLVED and mp.get("cik"):
            out.append(_hi.norm_cik(mp["cik"]))
    return sorted({c for c in out if c})


def _mapping_version(ctx: FundamentalJobContext) -> str:
    return (ctx.store.get_meta("stage101_mapping_version_hash")
            or ctx.store.get_meta("stage102_mapped_epoch") or "nomvh")


def _epoch(ctx: FundamentalJobContext) -> str:
    """A CHEAP, stable epoch key = (identity mapping-version, companyfacts archive
    hash). It changes only when the resolved mapping OR the owned archive genuinely
    changes, so each downstream measurement runs exactly once per epoch and
    re-runs honestly when the underlying evidence changes."""
    mvh = str(_mapping_version(ctx))[:12]
    ah = str(_companyfacts_hash(_cfg(ctx)) or "noarch")[:12]
    return "%s:%s" % (mvh, ah)


def _target_tags(ctx: FundamentalJobContext):
    from . import sec_companyfacts_index as _cfi
    return _cfi.default_target_tags()


