def _lane(*, withheld, available, reasons=None):
    return pdec.derive_decision_state(
        has_active_book=True,
        proposal_summary={"reallocation_proposal_available": available,
                          "reallocation_proposal_withheld": withheld,
                          "reallocation_withheld_reasons": reasons or [],
                          "reallocation_proposal_hash": WITHHELD_HASH},
        decision_record=None)


