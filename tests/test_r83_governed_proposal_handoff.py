r"""tests/test_r83_governed_proposal_handoff.py — R83: the terminal WITHHELD verdict
that no read surface could express.

THE DEFECT, as the live 2026-09-28 session recorded it.

The Portfolio Cycle ran and completed. Its ``BUILD_REALLOCATION_PROPOSAL`` step was
INVOKED, the economic gate had CLEARED (reassessment ``PROPOSAL_READY``), and
``api.reallocation_proposal`` built a complete alternative portfolio over 20 holdings,
re-optimised it under the breached limit and WITHHELD it: AMD 0.1503 and SNDK 0.1545
against the governed per-name risk-contribution cap 0.15. That is a COMPLETED,
fail-closed governed decision, and by the owner's own persistence contract it is never
written as an artifact (``STATE_WITHHELD_NOT_PERSISTABLE``).

Nothing downstream could say so. ``api.reallocation_proposal`` resolved its read state
from a PERSISTED artifact alone, so a session with no artifact always answered
``NOT_RUN`` — "the cycle never ran" — and, being the single source every other surface
composes, it made four surfaces lie at once:

  * Today                 PORTFOLIO PROPOSAL REQUESTED — NOT YET PRODUCED
  * Reallocation card     "the first proposal will be generated by the next completed
                          Daily Research Cycle", outstanding action
                          RUN_DAILY_RESEARCH_CYCLE
  * Decision review       "no proposal to review (read state NOT_RUN)",
                          NEXT REQUIRED ACTION = REFRESH THE REVIEW
  * Overview              "no feasible target was priced for this session"

Every one of those names an action that provably cannot change the verdict, and the
last one is false outright: a target WAS priced, and it cleared its economics
(+0.067127 net of cost) before a risk limit refused it.

``STATE_WITHHELD`` was declared in ``READ_STATE_VOCAB``, mapped by
``api.workflow_state`` to ``REALLOCATION_PROPOSAL_WITHHELD`` / "WITHHELD — PORTFOLIO
LIMITS", mapped by the canonical decision lane to ``CHANGE_CANDIDATE_WITHHELD`` / "NO
PROPOSAL — PORTFOLIO CHANGE WITHHELD", and policed by invariant I5. The entire
vocabulary was already in place and STRUCTURALLY UNREACHABLE, because the only state
source was a store that refuses to hold it. A declared state no store can produce is
not a state.

R83 closes the read seam: the governed run manifest — the ONE durable record of the
verdict — is consulted through the ONE canonical reference reader, and the verdict is
published VERBATIM. No second solver, no second index, no fabricated target, no
recomputed limit, and nothing becomes approvable.

EVERYTHING HERE IS HERMETIC. Every store root is a per-test ``tmp_path``. No network,
no provider, no prediction, no live store read on the paths under test, no Daily Close,
no operational-ledger write, no order / plan / fill, no approval, no selection, no
risk-policy ruling and no model promotion.
"""
