# 7. THE SAME UNREACHABLE-STATE DEFECT, ONE AND TWO LAYERS UP.
#
#    ``PDS_CHANGE_WITHHELD`` sat behind ``available`` — a term that means "a PERSISTED
#    artifact exists" and that a withheld verdict can never satisfy — so every withheld
#    session reached ``PDS_NO_PROPOSAL``. The reassessment card's own suppression keys
