UI = Path(__file__).resolve().parent.parent / "api" / "ui" / "index.html"


def _ui_src():
    return UI.read_text(encoding="utf-8", errors="replace")


def _ui_fn(src, name, end_marker):
    start = src.find("function " + name)
    assert start != -1, name
    end = src.find(end_marker, start)
    assert end != -1, end_marker
    return src[start:end]


