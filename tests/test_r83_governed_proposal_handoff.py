def _ps(*, book=BOOK, session=SESSION):
    """The minimum portfolio-state shape the read contract keys on."""
    return {"active_book": {"book_id": book, "book_label": book, "status": "ACTIVE",
                            "initialized": True, "holdings_count": 25},
            "dates": {"eligible_market_date": session}}


def _read(tmp, *, book=BOOK, session=SESSION):
    """The reallocation READ contract, bound to the hermetic stores only."""
    return rp.load_reallocation_proposal(portfolio_state=_ps(book=book, session=session),
                                         reallocation_dir=str(tmp / "realloc"),
                                         drc_dir=str(tmp))


def _summary(tmp, *, book=BOOK, session=SESSION):
    """The compact summary the gate -> workflow -> Today/Overview/Audit path uses."""
    return rp.load_proposal_summary(active_book_id=book, eligible_market_date=session,
                                    reallocation_dir=str(tmp / "realloc"),
                                    drc_dir=str(tmp))


def _card(tmp, *, reassessment_state="PROPOSAL_READY"):
    """The reallocation presentation card, fed exactly what the gate would forward."""
    s = _summary(tmp)
    return ws.build_reallocation_proposal_presentation(
        state=s["reallocation_proposal_state"],
        available=s["reallocation_proposal_available"],
        eligible_date=SESSION,
        action_counts=s["reallocation_action_counts"],
        proposal_hash=s["reallocation_proposal_hash"],
        proposed_holding_count=s["reallocation_proposed_holding_count"],
        one_way_turnover=s["reallocation_one_way_turnover"],
        estimated_transaction_cost=s["reallocation_estimated_transaction_cost"],
        cycle_complete=True, cycle_run_id="drc_test",
        reassessment_state=reassessment_state,
        withheld_outcome=s["reallocation_governed_withheld_outcome"])


def _decision(tmp, *, reassessment_state="PROPOSAL_READY"):
    """The ONE canonical portfolio-decision object the Today lane renders."""
    s = _summary(tmp)
    card = _card(tmp, reassessment_state=reassessment_state)
    return ws.build_canonical_portfolio_decision(
        reassessment_summary={"reassessment_state": reassessment_state,
                              "reassessment_available": True},
        reallocation_operator_state=card["canonical_operator_state"],
        portfolio_decision_lane={
            "reallocation_proposal_withheld": s["reallocation_proposal_withheld"],
            "withheld_reasons": s["reallocation_withheld_reasons"],
            "proposal_hash": s["reallocation_proposal_hash"]},
        attention_count=0, eligible_date=SESSION,
        withheld_outcome=s["reallocation_governed_withheld_outcome"])


def _review(tmp):
    """The Proposal Decision Review over the hermetic payload."""
    return pdr.load_proposal_decision_review(
        proposal_payload=_read(tmp), portfolio_state=_ps(),
        reallocation_dir=str(tmp / "realloc"), drc_dir=str(tmp),
        hoc_dir=str(tmp / "hoc"), outcome_dir=str(tmp / "out"),
        decision_dir=str(tmp / "dec"), latest_session=SESSION)


def _ready_result(*, hash_="ready_target_hash_r83", session=SESSION, book=BOOK):
    """A READY proposal in the kernel's own shape, for the success path."""
    return {
        "proposal_state": rpk.STATE_READY,
        "proposal_hash": hash_,
        "eligible_market_date": session,
        "active_book_id": book,
        "action_counts": {"RETAIN": 8, "INCREASE": 6, "REDUCE": 0, "EXIT": 11,
                          "ADD": 6, "REPLACE_OUT": 0, "REPLACE_IN": 0},
        "portfolio": {"proposed_holding_count": 20},
        "signal": {"score_improvement": 0.084627,
                   "score_improvement_net_of_cost": 0.067127},
        "turnover": {"one_way_turnover": 0.35, "estimated_transaction_cost": 85.97},
        "approvable": True,
        "withheld_reasons": [],
        "complete_target_limits": {"withheld": False, "all_ok": True},
        "data_gaps": [],
    }


def _persist_ready(tmp, **kw):
    return rp.persist_proposal(result=_ready_result(**kw),
                              input_contract={"active_book_id": kw.get("book", BOOK),
                                              "eligible_market_date": kw.get("session",
                                                                             SESSION)},
                              reallocation_dir=str(tmp / "realloc"))


def _artifacts(tmp):
    d = tmp / "realloc" / "artifacts"
    return sorted(p.name for p in d.glob("*.json")) if d.exists() else []


def _index(tmp):
    import json
    p = tmp / "realloc" / "index.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


